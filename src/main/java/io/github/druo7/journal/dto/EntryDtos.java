package io.github.druo7.journal.dto;

import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Size;
import io.github.druo7.journal.entity.JournalEntry;
import io.github.druo7.journal.entity.Sentiment;

import java.time.Instant;
import java.time.LocalDate;
import java.util.List;
import java.util.UUID;

import static io.github.druo7.journal.dto.AuthDtos.BASE64_REGEX;

public final class EntryDtos {
    private EntryDtos() {
    }

    /** ~150 KB of plaintext after base64 + GCM overhead; matches the DB check constraint. */
    public static final int MAX_CIPHERTEXT = 200_000;

    /**
     * @param id              generated by the client, because it is bound into the ciphertext as AAD
     * @param timeZone        the writer's IANA time zone; decides which day "today" is and when it ends
     * @param reportSentiment plaintext mood, only stored (server-encrypted) if the user opted in to the weekly email
     */
    public record CreateEntryRequest(
            @NotNull UUID id,
            @NotBlank @Size(max = 64) String timeZone,
            @NotBlank @Size(max = MAX_CIPHERTEXT) @Pattern(regexp = BASE64_REGEX) String ciphertext,
            @NotBlank @Size(min = 16, max = 24) @Pattern(regexp = BASE64_REGEX) String iv,
            Sentiment reportSentiment) {
    }

    /** @param version the version the client last saw; a stale value is rejected with 409 */
    public record UpdateEntryRequest(
            @NotBlank @Size(max = MAX_CIPHERTEXT) @Pattern(regexp = BASE64_REGEX) String ciphertext,
            @NotBlank @Size(min = 16, max = 24) @Pattern(regexp = BASE64_REGEX) String iv,
            Sentiment reportSentiment,
            @NotNull Long version) {
    }

    /** @param days the days written on in the last year, oldest first */
    public record ActivityResponse(List<LocalDate> days) {
    }

    /**
     * @param entryDate the day this entry belongs to
     * @param locksAt   when the entry becomes read-only (end of {@code entryDate} in the writer's time zone)
     * @param editable  whether it can still be changed right now
     */
    public record EntryResponse(UUID id, String ciphertext, String iv, int encVersion, long version,
                                LocalDate entryDate, Instant locksAt, boolean editable,
                                Instant createdAt, Instant updatedAt) {
        public static EntryResponse of(JournalEntry e, Instant now) {
            return new EntryResponse(e.getId(), e.getCiphertext(), e.getIv(), e.getEncVersion(), e.getVersion(),
                    e.getEntryDate(), e.getLocksAt(), e.isEditable(now), e.getCreatedAt(), e.getUpdatedAt());
        }
    }
}
